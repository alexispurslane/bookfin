// Writes lib/reader/epub/reader_coverage.dart: the coverage of the bundled
// reader font, which admission compares a book's own fonts with (boo-3huo).
//
// The table is written ahead, so that admission's worker reads no asset.
// test/reader/epub/book_fonts_test.dart fails when the table and the font
// disagree. After a change to the reader font, run it from the repository
// root in the dev shell:
//
//     dart run tool/reader/reader_coverage.dart
import 'dart:io';

import 'package:bookfin/reader/epub/font_files.dart';

const _font = 'assets/fonts/SourceSerif4.ttf';
const _output = 'lib/reader/epub/reader_coverage.dart';

void main() {
  final coverage = Coverage.of(File(_font).readAsBytesSync());
  if (coverage == null) {
    stderr.writeln('$_font has no character map that Bookfin reads.');
    exitCode = 1;
    return;
  }
  final ranges = coverage.ranges;
  final lines = StringBuffer();
  for (var at = 0; at < ranges.length; at += 2) {
    final first = _hex(ranges[at]);
    final last = _hex(ranges[at + 1]);
    lines
      ..writeln('  $first,')
      ..writeln('  $last,');
  }
  var points = 0;
  for (var at = 0; at < ranges.length; at += 2) {
    points += ranges[at + 1] - ranges[at] + 1;
  }
  File(_output).writeAsStringSync('''
// GENERATED by tool/reader/reader_coverage.dart from $_font.
// Do not edit by hand. Run the tool again after a change to the font.
import 'font_files.dart';

/// The characters that the reader font, Source Serif 4, has a glyph for:
/// $points code points in ${ranges.length ~/ 2} ranges.
const readerCoverage = Coverage([
$lines]);
''');
  stdout.writeln(
    'wrote $_output: $points code points, ${ranges.length ~/ 2} ranges',
  );
}

String _hex(int value) =>
    '0x${value.toRadixString(16).toUpperCase().padLeft(4, '0')}';
